    def defenses_table(self, types):
        w, r = self.w, self.r
        groups = defaultdict(list)
        for att in sorted(w.types):
            mult = 1.0
            for d in types:
                mult *= w.efficacy[att].get(d, 1.0)
            groups[mult].append(att)
        labels = [(0.0, "Immune (×0)"), (0.25, "Very resistant (×¼)"), (0.5, "Resistant (×½)"), (1.0, "Neutral (×1)"), (2.0, "Weak (×2)"), (4.0, "Very weak (×4)")]
        rows = []
        for mult, label in labels:
            if groups.get(mult):
                rows.append([label, r.type_badges(groups[mult])])
        return table(["Damage taken", "Attacking types"], rows)

    def evolution_section(self, sid, prefix):
        w, r = self.w, self.r
        # find family root
        root = sid
        seen = set()
        while w.species[root]["evolves_from"] and root not in seen:
            seen.add(root)
            root = w.species[root]["evolves_from"]
        edges = []
        stack = [root]
        visited = set()
        while stack:
            cur = stack.pop(0)
            if cur in visited:
                continue
            visited.add(cur)
            for evo in w.evolutions.get(cur, []):
                edges.append((cur, evo["to"], evo["method"]))
                stack.append(evo["to"])
        lines = []
        if not edges:
            lines.append("This Pokémon does not evolve.")
        else:
            for frm, to, vanilla in edges:
                method, changed = self.evo_method(frm, to, vanilla)
                a = r.mon_link(frm, prefix, bold=(frm == sid))
                b = r.mon_link(to, prefix, bold=(to == sid))
                line = f"- {a} → {b}: {method}"
                if changed:
                    line += f' <span class="chg">changed</span> <small>(vanilla: {esc(vanilla)})</small>'
                lines.append(line)
        megas = [f for f in self.w.species_forms[sid][1:] if self.w.pokemon[f]["is_mega"]]
        for pid in megas:
            p = w.pokemon[pid]
            stone = self.mega_stone(sid, p["form_name"])
            lines.append(f"- {r.sprite(pid, prefix, 'sprite-sm')} **{esc(p['form_name'])}**: {stone}")
        return "\n".join(lines) + "\n"

    def mega_stone(self, sid, form_name):
        r = self.r
        stone = mega_stone_name(self.w.species[sid]["name"], form_name)
