    def tm_label(self, name, prefix):
        mid = self.w.move_id(name)
        if not mid:
            return esc(name)
        label = self.w.machines.get(mid)
        return (f"{label} " if label else "") + self.r.move_link(mid, prefix)

    def item_evolves(self, item):
        w = self.w
        n = norm(item)
        out = []
        for sec in w.rrss["evolutions"]["sections"]:
            for row in sec["rows"]:
                if len(row) >= 4 and n in norm(row[3]):
                    out.append(f"{row[1]} → {row[2]}")
        return ", ".join(out) or "—"

    def shop_item(self, name, prefix):
        m = re.match(r"^(TM\d+) (.+)$", name)
        if m:
            return f"{m.group(1)} {self.r.move_ref(m.group(2), prefix)}"
        return self.r.item_ref(name, prefix)

    # ---------------------------------------------------------- navigation
    def nav(self):
        w = self.w
        lines = [
            "* [Home](index.md)",
            "* Pokémon",
            "    * [Pokédex](pokemon/index.md)",
            "    * [General Changes](changes/index.md)",
            "    * [Stat Changes](changes/stats.md)",
            "    * [Type Changes](changes/types.md)",
            "    * [Ability Changes](changes/abilities.md)",
            "    * [Evolution Changes](changes/evolutions.md)",
            "    * [Move Changes](changes/moves.md)",
            "    * [TM & Tutor Changes](changes/learnsets.md)",
            "    * [Held Item Changes](changes/held_items.md)",
            "    * [Other Changes](changes/other.md)",
            "    * Specific Changes",
        ]
        regions = [("Kanto", 1, 151), ("Johto", 152, 251), ("Hoenn", 252, 386), ("Sinnoh", 387, 493), ("Unova", 494, 649), ("Kalos", 650, 721)]
        for region, lo, hi in regions:
            lines.append(f"        * {region} (#{lo:03d}–#{hi:03d})")
            for sid in range(lo, hi + 1):
                lines.append(f"            * [#{sid:03d} {w.species[sid]['name']}](pokemon/{sid:03d}.md)")
        lines.append("* Wild Pokémon")
        lines.append("    * [General](wild/index.md)")
        for section in ("Main Game", "Post Game"):
            lines.append(f"    * {section}")
            for a in [a for a in w.areas if a["has_wild"] and a["section"] == section]:
                lines.append(f"        * [{a['display']}](wild/{a['slug']}.md)")
        lines.append("* Trainers")
        lines.append("    * [General](trainers/index.md)")
        lines.append("    * [Boss Battles](trainers/bosses.md)")
        for section in ("Main Game", "Post Game"):
            lines.append(f"    * {section}")
            for a in [a for a in w.areas if a["has_trainers"] and a["section"] == section]:
                lines.append(f"        * [{a['display']}](trainers/{a['slug']}.md)")
        lines += [
            "* [Item Changes](changes/items.md)",
            "* [Gifts & Static Encounters](changes/gifts_and_statics.md)",
            "* [FAQ](faq.md)",
            "* [About](about.md)",
        ]
        content = "\n".join(lines) + "\n"
        path = SITE_DOCS / "SUMMARY.md"
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            path.write_text(content, encoding="utf-8")
            self.changed += 1

    def run(self):
        for sid in sorted(self.w.species):
            self.pokemon_page(sid)
        self.pokedex_index()
        self.wild_pages()
        self.trainer_pages()
        self.change_pages()
        self.nav()
        # remove generated pages that no longer exist (e.g. a renamed area)
        removed = 0
        for sub in ("pokemon", "wild", "trainers", "changes"):
            for path in (SITE_DOCS / sub).glob("*.md"):
                if path not in self.written:
                    path.unlink()
                    removed += 1
        return self.changed, removed


